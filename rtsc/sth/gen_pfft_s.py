# Generate sth_pfft_s.f90 (FP32 twin) from sth_pfft.f90.  python3 gen_pfft_s.py  (run in rtsc/sth)
s = open('sth_pfft.f90').read()
hdr_old = s[:s.index("MODULE sth_pfft")]
hdr = """!
! rtsc: FP32 twin of sth_pfft.f90, GENERATED by gen_pfft_s.py (edit sth_pfft.f90 and regenerate).
! Used by the mixed-precision engine (RTSC_STH_MP=1) for its FP32 operator applications with
! RTSC_STH_PFFT=1: complex/real data in single precision, e_n read in FP64 and rounded as
! k_gather_h_s does.
!
"""
s = hdr + s[len(hdr_old):]
def rep(a, b, need=True):
    global s
    if need: assert a in s, a[:80]
    s = s.replace(a, b)
rep("MODULE sth_pfft", "MODULE sth_pfft_s")
rep("  INTEGER, PARAMETER :: dp = SELECTED_REAL_KIND(14, 200)\n",
    "  INTEGER, PARAMETER :: dp = SELECTED_REAL_KIND(14, 200), sp = SELECTED_REAL_KIND(6, 37)\n")
for a, b in [("pfft_setup", "pfs_setup"), ("pfft_free", "pfs_free"), ("pfft_local", "pfs_local"), ("pfft_ok", "pfs_ok"),
             ("pfft_info", "pfs_info"), ("k_pz_inv", "ks_pz_inv"), ("k_pxy", "ks_pxy"), ("k_pz_fwd", "ks_pz_fwd"),
             ("SUBROUTINE bfly", "SUBROUTINE bfly_s"), ("CALL bfly(", "CALL bfly_s("), ("SUBROUTINE bstore", "SUBROUTINE bstore_s"),
             ("CALL bstore(", "CALL bstore_s("), ("SUBROUTINE wfft", "SUBROUTINE wfft_s"), ("CALL wfft(", "CALL wfft_s("),
             ("SUBROUTINE factor", "SUBROUTINE factor_s"), ("CALL factor(", "CALL factor_s(")]:
    rep(a, b)
rep("COMPLEX(dp)", "COMPLEX(sp)")
rep("(0.0_dp, 0.0_dp)", "(0.0_sp, 0.0_sp)")
for v in ["t3", "t4", "c1", "c2"]:
    rep("CMPLX(-AIMAG(%s), REAL(%s), dp)" % (v, v), "CMPLX(-AIMAG(%s), REAL(%s), sp)" % (v, v))
b0 = s.index("SUBROUTINE bfly_s("); b1 = s.index("END SUBROUTINE bfly_s")
blk = s[b0:b1].replace("REAL(dp), PARAMETER", "REAL(sp), PARAMETER").replace("_dp", "_sp").replace(
    "REAL(dp) :: sg", "REAL(sp) :: sg").replace("sg = REAL(sgn, dp)", "sg = REAL(sgn, sp)")
s = s[:b0] + blk + s[b1:]
rep("    REAL(dp) :: v(*)\n", "    REAL(sp) :: v(*)\n")
rep("""    INTEGER, VALUE :: s0, nslot, npert, npwx, nksq, nbnd, nst, n3, nzst, nf3, lbz
    REAL(dp), VALUE :: scale""", """    INTEGER, VALUE :: s0, nslot, npert, npwx, nksq, nbnd, nst, n3, nzst, nf3, lbz
    REAL(sp), VALUE :: scale""")
rep("""    REAL(dp) :: g2(npwx, nksq), etk(nbnd, nksq)
    COMPLEX(sp), SHARED :: sm(0:*)""", """    REAL(sp) :: g2(npwx, nksq)
    REAL(dp) :: etk(nbnd, nksq)
    COMPLEX(sp), SHARED :: sm(0:*)""")
rep("y(ig, col) = g2(ig, k) * xv + sm(sl + (GS + 1) * i3) * scale - etk(n, k) * xv",
    "y(ig, col) = g2(ig, k) * xv + sm(sl + (GS + 1) * i3) * scale - REAL(etk(n, k), sp) * xv")
rep("""    REAL(dp), DEVICE :: vrs(*), g2(npwx, nksq), etk(nbnd, nksq)
    REAL(dp), INTENT(IN) :: scale""", """    REAL(sp), DEVICE :: vrs(*), g2(npwx, nksq)
    REAL(dp), DEVICE :: etk(nbnd, nksq)
    REAL(sp), INTENT(IN) :: scale""")
rep("    shm_xy = 16 * ld * n2", "    shm_xy = 8 * ld * n2")
rep("    shm_z = 16 * (", "    shm_z = 8 * (")
for d in ["n1), SIN(tpi * d / n1), dp)", "n2), SIN(tpi * d / n2), dp)", "n3), SIN(tpi * d / n3), dp)"]:
    rep(d, d.replace("dp)", "sp)"))
rep("(freeb / 8) / (16_8 * nzst)", "(freeb / 8) / (8_8 * nzst)")
rep("'sth_pfft: launch failed: '", "'sth_pfft_s: launch failed: '")
open('sth_pfft_s.f90', 'w').write(s)
print("wrote sth_pfft_s.f90")
